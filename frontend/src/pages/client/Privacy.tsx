import type { ReactNode } from "react";
import { Card, Screen } from "../../components/ui";
import { useSession } from "../../lib/session";

export const POLICY_EDITION = "31 октября 2026 г.";

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <Card className="space-y-2 text-[15px] leading-relaxed">
      <h2 className="font-semibold">{title}</h2>
      {children}
    </Card>
  );
}

/** Политика обработки персональных данных (152-ФЗ). Реквизиты оператора берутся из настроек. */
export default function Privacy() {
  const { info } = useSession();
  const operator = info.operator_name || info.master_name || "Оператор (ФИО указывается в настройках)";
  const contacts = [
    info.privacy_email && `эл. почта ${info.privacy_email}`,
    info.contact_telegram && `Telegram ${info.contact_telegram}`,
    info.contact_phone && `телефон ${info.contact_phone}`,
  ].filter(Boolean).join(", ");

  return (
    <Screen title="Политика конфиденциальности" back={true}>
      <p className="text-sm text-muted">
        Политика обработки персональных данных сервиса онлайн-записи «{info.studio_name}». Редакция от {POLICY_EDITION}
      </p>

      <Section title="1. Кто обрабатывает данные">
        <p>
          Оператор персональных данных: <b>{operator}</b>
          {info.operator_inn && <>, ИНН {info.operator_inn}</>}
          {info.address && <>, адрес оказания услуг: {info.address}</>}.
        </p>
        <p>Связаться по вопросам персональных данных: {contacts || "через чат с ботом записи"}.</p>
      </Section>

      <Section title="2. Какие данные мы храним">
        <ul className="list-disc space-y-1 pl-5">
          <li>имя — из Telegram или указанное вами;</li>
          <li>номер телефона;</li>
          <li>Telegram ID и имя пользователя (@username) — для входа и сообщений от бота;</li>
          <li>записи: услуга, дата и время, стоимость, статус, ваш комментарий к записи;</li>
          <li>служебные заметки мастера о визитах (без медицинских сведений);</li>
          <li>отметки об отправке напоминаний и дата вашего согласия с этой политикой.</li>
        </ul>
        <p>Мы не собираем паспортные данные, сведения о здоровье, геолокацию и не используем рекламные cookies.</p>
      </Section>

      <Section title="3. Зачем">
        <ul className="list-disc space-y-1 pl-5">
          <li>записать вас на массаж, перенести или отменить запись;</li>
          <li>связаться с вами по поводу записи;</li>
          <li>прислать подтверждение и напоминания о визите (их можно выключить в профиле);</li>
          <li>вести историю визитов.</li>
        </ul>
        <p>
          Основание — ваше согласие и оказание услуги по вашей записи (п. 1 и 5 ч. 1 ст. 6 Федерального закона
          № 152-ФЗ «О персональных данных»). Рассылок и рекламы нет.
        </p>
      </Section>

      <Section title="4. Кому передаются">
        <p>
          Данные не продаются и не передаются третьим лицам. Их видят только мастер и администратор записи. Сообщения
          бота доставляются через Telegram, а сами данные хранятся на арендованном сервере хостинг-провайдера.
        </p>
      </Section>

      <Section title="5. Сколько храним">
        <p>
          Пока вы пользуетесь записью или до отзыва согласия. После запроса на удаление данные удаляются сразу, но не
          позднее 30 дней. Из резервных копий они пропадают в течение 14 дней.
        </p>
        <p>
          После удаления в расписании остаётся только обезличенная отметка о прошедших визитах («Клиент удалён») без
          имени, телефона и Telegram.
        </p>
      </Section>

      <Section title="6. Ваши права">
        <ul className="list-disc space-y-1 pl-5">
          <li>узнать, какие данные о вас хранятся, — всё видно в разделах «Профиль» и «Мои записи»;</li>
          <li>исправить имя и телефон в профиле;</li>
          <li>
            отозвать согласие и удалить данные — кнопкой «Удалить мои данные» в профиле или написав оператору
            (ответим в течение 10 рабочих дней);
          </li>
          <li>обратиться в Роскомнадзор, если считаете, что ваши права нарушены.</li>
        </ul>
      </Section>

      <Section title="7. Как защищаем">
        <p>
          Соединение шифруется (HTTPS), вход только через Telegram с проверкой подписи, доступ к данным клиентов есть
          только у администратора. Резервные копии хранятся на том же защищённом сервере.
        </p>
      </Section>

      <Section title="8. Согласие">
        <p>
          Отмечая галочку при первой записи, вы даёте согласие на обработку перечисленных данных для указанных целей.
          Если политика изменится, новая редакция появится на этой странице.
        </p>
      </Section>
    </Screen>
  );
}
